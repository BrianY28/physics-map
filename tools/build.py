#!/usr/bin/env python3
"""Check every node file and generate the map's outputs.

  python3 tools/build.py           check, then write INDEX.md, map.opml and site/
  python3 tools/build.py --check   check, and fail if INDEX.md or map.opml are out of date (used by GitHub)

Python 3.9+, standard library only.
"""
import datetime, html, json, shutil, sys
from pathlib import Path
from xml.sax.saxutils import quoteattr

sys.path.insert(0, str(Path(__file__).resolve().parent))
import nodelib  # noqa: E402

ROOT = nodelib.ROOT
REPO = "https://github.com/BrianY28/physics-map"
SITE_URL = "https://briany28.github.io/physics-map/"
MAP_TITLE = "Physics: From Newton to the Frontier"
MARKMAP = "https://cdn.jsdelivr.net/npm/markmap-autoloader@0.18.12"  # pinned
STALE_DAYS = 365
GENERATED = "<!-- Generated by tools/build.py from nodes/. Do not edit by hand; edit the node files instead. -->"


def warnings(branches, today):
    out = []
    for b in branches:
        for n in b["nodes"]:
            if n.get("status") == "open":
                age = (today - datetime.date.fromisoformat(str(n["as_of"]))).days
                if age > STALE_DAYS:
                    out.append(f"{n['path']}: open node last checked {age} days ago (as_of {n['as_of']}); please re-check it")
    return out


def explainer_url(node, concept):
    name = Path(concept["explainer"]).name or Path(concept["explainer"]).parent.name
    return f"{SITE_URL}explainers/{name.strip('/')}/"


def index_md(branches):
    nodes = sum(len(b["nodes"]) for b in branches)
    concepts = sum(len(n["concepts"]) for b in branches for n in b["nodes"])
    reviewed = sum(1 for b in branches for n in b["nodes"] if any("(AI)" not in r for r in n.get("reviewed_by", [])))
    L = [GENERATED, "", "# Index", "",
         f"{len(branches)} branches, {nodes} nodes, {concepts} concepts. "
         f"{reviewed} of {nodes} nodes have been reviewed by a person. "
         f"[Open the interactive map]({SITE_URL}).", ""]
    for b in branches:
        L += [f"## [{b['title']}]({b['path']})", "", f"{b['span']} · {b['summary']}", "",
              "| Node | When | Status | Concepts | Sources | Reviewed by |", "| --- | --- | --- | --- | --- | --- |"]
        for n in b["nodes"]:
            status = "open, as of " + str(n["as_of"]) if n["status"] == "open" else "established"
            names = []
            for c in n["concepts"]:
                names.append(f"{c['title']} ([explainer]({explainer_url(n, c)}))" if "explainer" in c else c["title"])
            L.append(f"| [{n['title']}]({n['path']}) | {n['when']} | {status} | {'; '.join(names)} | "
                     f"{len(n['sources'])} | {', '.join(n.get('reviewed_by', []))} |")
        L.append("")
    return "\n".join(L)


def opml(branches):
    L = ['<?xml version="1.0" encoding="UTF-8"?>', '<opml version="2.0">',
         f"  <head><title>{html.escape(MAP_TITLE)}</title></head>", "  <body>",
         f"    <outline text={quoteattr(MAP_TITLE)} _note={quoteattr('Open source: ' + REPO)}>"]
    for b in branches:
        L.append(f"      <outline text={quoteattr(b['title'])} _note={quoteattr(b['span'] + ' · ' + b['summary'])}>")
        for n in b["nodes"]:
            meta = str(n["when"]) + (" · " + ", ".join(n["people"]) if n.get("people") else "")
            if n["status"] == "open":
                meta += f" · open question, as of {n['as_of']}"
            note = meta + "\n" + n["note"] + "\nSources:\n" + "\n".join("- " + s for s in n["sources"])
            L.append(f"        <outline text={quoteattr(n['title'])} _note={quoteattr(note)}>")
            for c in n["concepts"]:
                cnote = c["note"] + (f"\nExplainer: {explainer_url(n, c)}" if "explainer" in c else "")
                L.append(f"          <outline text={quoteattr(c['title'])} _note={quoteattr(cnote)}/>")
            L.append("        </outline>")
        L.append("      </outline>")
    L += ["    </outline>", "  </body>", "</opml>"]
    return "\n".join(L) + "\n"


def markmap_md(branches):
    def esc(s):
        return s.replace("[", "\\[").replace("]", "\\]").replace("<", "&lt;")
    L = ["---", "markmap:", "  initialExpandLevel: 3", "  colorFreezeLevel: 2", "  maxWidth: 320", "---",
         f"# {esc(MAP_TITLE)}"]
    for b in branches:
        L.append(f"## [{esc(b['title'])}]({REPO}/tree/main/nodes/{b['dir']}) <small>{esc(b['span'])}</small>")
        for n in b["nodes"]:
            tag = " <small>open</small>" if n["status"] == "open" else ""
            L.append(f"### [{esc(n['title'])}]({REPO}/blob/main/{n['path']}){tag}")
            for c in n["concepts"]:
                link = f" · [explainer](explainers/{Path(c['explainer']).name}/)" if "explainer" in c else ""
                L.append(f"- {esc(c['title'])}{link}")
    return "\n".join(L)



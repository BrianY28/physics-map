def build_site(branches, index, opml_text):
    site = ROOT / "site"
    if site.exists():
        shutil.rmtree(site)
    site.mkdir()
    nodes = sum(len(b["nodes"]) for b in branches)
    stats = f"{len(branches)} branches, {nodes} nodes, from Newton to the open frontier."
    md = markmap_md(branches).replace("</script", "<\\/script")
    page = (SITE_PAGE.replace("__STATS__", html.escape(stats)).replace("__REPO__", REPO)
            .replace("__MARKMAP__", MARKMAP).replace("__MARKDOWN__", md))
    (site / "index.html").write_text(page)
    (site / "map.opml").write_text(opml_text)
    (site / ".nojekyll").write_text("")
    for frag in sorted((ROOT / "explainers").glob("*/index.html")):
        dest = site / "explainers" / frag.parent.name / "index.html"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(EXPLAINER_PAGE.replace("__FRAGMENT__", frag.read_text()))
    return site


def main():
    check = "--check" in sys.argv
    try:
        branches = nodelib.load()
    except nodelib.NodeError as e:
        print(f"error: {e}")
        return 1
    errs = nodelib.validate(branches)
    for w in warnings(branches, datetime.date.today()):
        print(f"warning: {w}")
    if errs:
        print("\n".join(f"error: {e}" for e in errs))
        print(f"{len(errs)} problem(s) found. See CONTRIBUTING.md for the file format.")
        return 1
    index, opml_text = index_md(branches) + "\n", opml(branches)
    nodes = sum(len(b["nodes"]) for b in branches)
    if check:
        stale = [name for name, text in (("INDEX.md", index), ("map.opml", opml_text))
                 if not (ROOT / name).exists() or (ROOT / name).read_text() != text]
        if stale:
            print(f"error: {', '.join(stale)} out of date. Run: python3 tools/build.py, then commit the result.")
            return 1
        print(f"ok: {len(branches)} branches, {nodes} nodes; generated files are up to date")
        return 0
    (ROOT / "INDEX.md").write_text(index)
    (ROOT / "map.opml").write_text(opml_text)
    site = build_site(branches, index, opml_text)
    print(f"ok: {len(branches)} branches, {nodes} nodes; wrote INDEX.md, map.opml and {site.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
